#!/usr/bin/env python3
"""ESD pad-clamp diode bench: request generator, area derivation, wording check.

  esd_clamp.py gen    --out DIR [--pdk-root PATH] [--backend NAME] [--bad-lib]
  esd_clamp.py derive --fwd R --leak R --cap R --grid DIR/grid.json --out DIR --meta K=V ...
  esd_clamp.py wording-check FILE_OR_DIR ...
  esd_clamp.py selftest

Pure stdlib. Run with `python3 -I`. See sim/esd_clamp/README.md.
"""
import argparse, gzip, json, math, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = os.path.join(HERE, "..", "..", "spec", "io-ring.md")

# Swept geometry: 33 areas, 10^(1/8) apart, 1e-11 .. 1e-7 m^2 (10 .. 1e5 um^2).
# Perimeter is a square's (4*sqrt(A)); see the record's assumptions.
AREAS = [10 ** (-11 + k / 8) for k in range(33)]
CURRENTS = [0.0, 0.01, 0.05, 0.1, 0.25, 0.5, 0.75, 1.0, 1.33, 1.5, 2.0]  # A
I_HBM = 1.33  # A, 2 kV / 1.5 kohm = 1.333 A, rounded down as in issue #11
BUDGETS = [2.5, 3.0, 3.5]  # V; BUDGETS[1] is the one used, the others show sensitivity
BUDGET = BUDGETS[1]
CAP_TARGET = 3e-12  # F, spec/io-ring.md pad table "added capacitance"
F_AC = 1e6  # Hz, small-signal capacitance extraction frequency
V_REV = 5.5  # V, DVDD max
DEVICES = {"nd": "diode_nd2ps_06v0", "pd": "diode_pd2nw_06v0"}
# (corner name in the request, .lib section)
PROCESS = [("typical", "diode_typical"), ("ff", "diode_ff"), ("ss", "diode_ss")]
TEMPS = [-40, 25, 125]


def aname(k):
    return "a%02d" % k


def pj(area):
    return 4 * math.sqrt(area)


def netlist():
    L = ["* ESD pad-clamp diode bench (circuit body; klt sim owns .control/.end).",
         "* Generated by sim/esd_clamp/esd_clamp.py. Diodes are two-terminal: forward bias",
         "* is anode-high whichever way the pad connects, so every forward diode is",
         "* instantiated anode=node, cathode=0 and driven by a current source.",
         "* Reverse bank: cathode at rn through a 0 V ammeter (dc leakage) and a 1 ohm",
         "* sense resistor (ac: the source is ideal, so Im V(r) = -Im(I)*1 ohm and C = -Im V(r) / (2*pi*f)).",
         "Vs s 0 0",
         "Vr rn 0 0 ac 1"]
    for d, model in DEVICES.items():
        for k, a in enumerate(AREAS):
            g = "area=%.6g pj=%.6g" % (a, pj(a))
            n = "%s_%s" % (d, aname(k))
            L.append("Bf_%s 0 f_%s I=v(s)" % (n, n))
            L.append("Df_%s f_%s 0 %s %s" % (n, n, model, g))
            L.append("Vm_%s rn m_%s 0" % (n, n))
            L.append("Rm_%s m_%s r_%s 1" % (n, n, n))
            L.append("Dr_%s 0 r_%s %s %s" % (n, n, model, g))
    return "\n".join(L) + "\n"


def requests(pdk_root, backend, bad_lib):
    """Three plain requests (dc forward, dc reverse, ac): only plain features (.meas cards,
    no analysis_steps/expr)."""
    lib = "libs.tech/ngspice/" + ("does-not-exist.ngspice" if bad_lib else "sm141064.ngspice")
    models = {"pdk": "gf180mcuD", "lib": lib}
    if pdk_root:
        models["pdk_root"] = pdk_root
    names = ["%s_%s" % (d, aname(k)) for d in DEVICES for k in range(len(AREAS))]
    corners = {"process": [{"name": n, "sections": [s]} for n, s in PROCESS],
               "temperature_c": TEMPS}

    def base(meas, analysis, extra_corners=None):
        r = {"netlist": "esd_clamp.spice", "engine": "ngspice", "models": models,
             "corners": dict(corners, **(extra_corners or {})),
             "analysis": analysis, "measurements": meas,
             "options": {"timeout_s": 1800, "keep_artifacts": False}}
        if backend:
            r["backend"] = backend
        return r

    fwd = [{"name": "v_%s_i%d" % (n, j),
            "spice": ".meas dc v_%s_i%d FIND v(f_%s) AT=%g" % (n, j, n, i), "unit": "V"}
           for n in names for j, i in enumerate(CURRENTS)]
    leak = [{"name": "i_%s" % n,
             "spice": ".meas dc i_%s FIND i(vm_%s) AT=%g" % (n, n, V_REV), "unit": "A"}
            for n in names]
    cap = [{"name": "c_%s" % n,
            "spice": ".meas ac c_%s FIND vi(r_%s) AT=%g" % (n, n, F_AC), "unit": "V"}
           for n in names]
    return {
        "fwd": base(fwd, {"kind": "dc", "args": "Vs 0 2 0.01"}),
        "leak": base(leak, {"kind": "dc", "args": "Vr 0 %g 0.5" % V_REV}),
        # Vr bias is a supply axis so the one ac request covers both 0 V and 5.5 V.
        "cap": base(cap, {"kind": "ac", "args": "lin 3 %g %g" % (F_AC / 2, F_AC * 1.5)},
                    {"supply_v": {"vr": [0, V_REV]}}),
    }


def cmd_gen(a):
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "esd_clamp.spice"), "w") as f:
        f.write(netlist())
    for k, r in requests(a.pdk_root, a.backend, a.bad_lib).items():
        with open(os.path.join(a.out, "request_%s.json" % k), "w") as f:
            json.dump(r, f, indent=1)
    with open(os.path.join(a.out, "grid.json"), "w") as f:
        json.dump({"areas_m2": AREAS, "pj_m": [pj(x) for x in AREAS], "currents_a": CURRENTS,
                   "devices": DEVICES, "process": PROCESS, "temps_c": TEMPS,
                   "i_hbm_a": I_HBM, "budgets_v": BUDGETS, "v_rev": V_REV,
                   "f_ac_hz": F_AC, "cap_target_f": CAP_TARGET}, f, indent=1)


# ---------------------------------------------------------------- derivation

def spec_quote():
    """The ESD-evidence limitation paragraph from the spec, verbatim."""
    t = open(SPEC).read().split("\n")
    i = next(k for k, l in enumerate(t) if l.strip() == "### ESD evidence")
    j = i + 1
    while not t[j].strip():
        j += 1
    k = j
    while t[k].strip():
        k += 1
    return t[j:k], j + 1, k  # lines, first and last 1-based line numbers


def load_report(path):
    opener = gzip.open if path.endswith(".gz") else open
    return json.load(opener(path, "rt"))


def corner_rows(report):
    """-> {(process, temp, vr or None): {measurement name: value, '_status': s}}."""
    rows = {}
    for c in report["corners"]:
        key = (c.get("process"), c.get("temperature_c"), (c.get("supply_v") or {}).get("vr"))
        rows[key] = {m["name"]: m.get("value") for m in c.get("measurements", [])}
        rows[key]["_status"] = c.get("status")
    return rows


def first_ok(areas_v, budget):
    """Smallest swept area whose forward drop is <= budget, or None. No interpolation."""
    for k, v in enumerate(areas_v):
        if v is not None and v <= budget:
            return k
    return None


def cmd_derive(a):
    reports = {"fwd": load_report(a.fwd), "leak": load_report(a.leak), "cap": load_report(a.cap)}
    report = reports["fwd"]
    g = json.load(open(a.grid))
    rows = {k: corner_rows(r) for k, r in reports.items()}
    areas = g["areas_m2"]
    problems = []
    need = {"fwd": [(p, t, None) for p, _ in g["process"] for t in g["temps_c"]],
            "leak": [(p, t, None) for p, _ in g["process"] for t in g["temps_c"]],
            "cap": [(p, t, float(v)) for p, _ in g["process"] for t in g["temps_c"] for v in (0, g["v_rev"])]}
    for k, keys in need.items():
        for c in keys:
            hit = next((x for x in rows[k] if x[:2] == c[:2] and (c[2] is None or (x[2] is not None and abs(x[2] - c[2]) < 1e-9))), None)
            if hit is None:
                problems.append("%s: missing corner %s" % (k, c))
            elif rows[k][hit]["_status"] != "pass":
                problems.append("%s: corner %s status %r" % (k, c, rows[k][hit]["_status"]))
    if problems:
        print("derive: FAIL: " + "; ".join(problems), file=sys.stderr)
        return 1
    corners = [(p, t) for p, _ in g["process"] for t in g["temps_c"]]

    def finite(v):
        return v if isinstance(v, (int, float)) and math.isfinite(v) else None

    def val(c, name):
        return finite(next(r for x, r in rows["fwd"].items() if x[:2] == c).get(name))

    def mval(c, step, name):
        if step == "leak":
            return finite(next(r for x, r in rows["leak"].items() if x[:2] == c).get(name))
        vr = 0.0 if step == "c0" else float(g["v_rev"])
        r = next(r for x, r in rows["cap"].items() if x[:2] == c and abs((x[2] or 0) - vr) < 1e-9)
        v = finite(r.get(name))
        return None if v is None else -v / (2 * math.pi * g["f_ac_hz"])  # 1 ohm sense: C = -Im V / w

    j_h = g["currents_a"].index(g["i_hbm_a"])
    out = []
    w = out.append
    quote, q0, q1 = spec_quote()
    w("# ESD pad-clamp diode sizing record")
    w("")
    for kv in a.meta:
        w("- " + kv.replace("=", ": ", 1))
    env = report.get("environment", {})
    w("- engine: %s %s (host: %s)" % (env.get("engine"), env.get("engine_version"), env.get("engine_host")))
    w("- klt: %s" % report.get("provenance", {}).get("klt_version"))
    w("- backend: %s" % (env.get("backend"),))
    for k, r in reports.items():
        rm = (r.get("environment") or {}).get("remote") or {}
        w("- %s request: remote job %s, runner klt %s, ngspice %s" % (
            k, rm.get("job_id"), rm.get("runner_klt_version"), (r.get("environment") or {}).get("engine_version")))
    w("")
    w("## Limitation (quoted from spec/io-ring.md lines %d-%d)" % (q0, q1))
    w("")
    for l in quote:
        w("> " + l)
    w("")
    w("This record is a diode-model sweep. It does not establish any HBM or CDM")
    w("robustness figure, and it says nothing about the spread of thick-oxide MOS")
    w("devices: the diode process sections used here (`diode_typical`/`diode_ff`/")
    w("`diode_ss`) scale the diode area-current, series-resistance and capacitance")
    w("parameters only, and DR-0002 records that the 5/6 V FETs do not skew.")
    w("")
    w("## Assumptions")
    w("")
    w("1. **Stress current.** The spec states only 'HBM 2 kV, design target only'.")
    w("   The 1.33 A figure is the standard human-body-model arithmetic")
    w("   2 kV / 1.5 kohm = 1.333 A, taken here as a stated assumption, not a spec value.")
    w("2. **Forward-drop budget = %.1f V.** The devices are the 6.0 V class diodes (the model" % BUDGET)
    w("   header says '6.0V N+/Psub diode'; that is a label, not a parameter. The cards carry")
    w("   `bv = 11` (nd2ps) and `bv = 10.5` (pd2nw), which are reverse breakdown and are not")
    w("   used here). The budget is half of the 6.0 V class, leaving the other half for the")
    w("   rail clamp, which is not chosen yet. It covers the diode's forward drop only.")
    w("   Derived areas at %.1f V and %.1f V are tabulated so the sensitivity is visible." % (BUDGETS[0], BUDGETS[2]))
    w("3. **Geometry.** Square diode: `pj = 4*sqrt(area)`. Area swept 1e-11 .. 1e-7 m^2,")
    w("   33 points, ratio 10^(1/8). The derived area is the smallest *swept* area that meets")
    w("   the budget (no interpolation). 'none' means no swept area meets it.")
    w("4. **Model extrapolation.** %.2f A through a model characterized at far lower currents" % g["i_hbm_a"])
    w("   is extrapolation: high injection and self-heating are not modeled, and the 'IKK too")
    w("   small' notice from ngspice's level-3 diode is expected. Treat the I-V above the")
    w("   knee current as a trend, not a measurement.")
    w("5. **Capacitance** is the sum of both clamp diodes' junction capacitance (both sit on")
    w("   the pad), from an ac solve at %g MHz with the diodes reverse biased at 0 V and %.1f V," % (g["f_ac_hz"] / 1e6, g["v_rev"]))
    w("   against the spec's <= 3 pF added-capacitance target. The ac source is ideal and the")
    w("   diode sits behind a 1 ohm sense resistor, so C = -Im V(sense node) / (2*pi*f); the")
    w("   error from the 1 ohm is below 0.1 percent for these sizes. Reverse leakage at %.1f V is" % g["v_rev"])
    w("   information only; the spec sets no leakage target. Values near 5.5 pA are the")
    w("   simulator's gmin floor (1e-12 S x 5.5 V), not diode leakage: the model's saturation")
    w("   current at these areas is far below it, so read leakage as 'at or below the floor'.")
    w("")

    # derived areas
    result = {}
    for d, model in g["devices"].items():
        result[d] = {}
        for c in corners:
            vh = [val(c, "v_%s_%s_i%d" % (d, aname(k), j_h)) for k in range(len(areas))]
            result[d][c] = {b: first_ok(vh, b) for b in g["budgets_v"]}
    w("## Derived area per device per corner (forward drop at %.2f A <= %.1f V)" % (g["i_hbm_a"], BUDGET))
    w("")
    w("| device | process | temp C | area m^2 | area um^2 | Vf at %.2f A (V) |" % g["i_hbm_a"])
    w("|---|---|---|---|---|---|")
    binding = {}
    for d, model in g["devices"].items():
        worst = None
        for c in corners:
            k = result[d][c][BUDGET]
            if k is None:
                w("| %s | %s | %s | none | none | - |" % (model, c[0], c[1]))
                worst = ("none", c, None)
            else:
                v = val(c, "v_%s_%s_i%d" % (d, aname(k), j_h))
                w("| %s | %s | %s | %.3g | %.3g | %.3f |" % (model, c[0], c[1], areas[k], areas[k] * 1e12, v))
                # binding = largest area; ties go to the corner with the least margin (highest Vf)
                if worst is None or (worst[0] != "none" and (k, v) > (worst[0], worst[2])):
                    worst = (k, c, v)
        binding[d] = worst
    w("")
    w("## Binding corner (largest area needed)")
    w("")
    w("| device | binding process | temp C | area m^2 | area um^2 |")
    w("|---|---|---|---|---|")
    for d, model in g["devices"].items():
        k, c, _ = binding[d]
        if k == "none":
            w("| %s | %s | %s | none within swept range | - |" % (model, c[0], c[1]))
        else:
            w("| %s | %s | %s | %.3g | %.3g |" % (model, c[0], c[1], areas[k], areas[k] * 1e12))
    w("")
    w("## Sensitivity to the budget (binding-corner area, um^2)")
    w("")
    w("| device | " + " | ".join("%.1f V" % b for b in g["budgets_v"]) + " |")
    w("|---|" + "---|" * len(g["budgets_v"]))
    for d, model in g["devices"].items():
        cells = []
        for b in g["budgets_v"]:
            ks = [result[d][c][b] for c in corners]
            cells.append("none" if None in ks else "%.3g" % (areas[max(ks)] * 1e12))
        w("| %s | %s |" % (model, " | ".join(cells)))
    w("")

    # capacitance and leakage at the binding areas
    ok = all(binding[d][0] != "none" for d in g["devices"])
    w("## Capacitance and leakage at the binding-corner areas")
    w("")
    if not ok:
        w("Not evaluated: at least one device has no swept area that meets the budget.")
        capsum = None
    else:
        w("Each device is evaluated at its own binding-corner area, in every corner.")
        w("")
        w("| process | temp C | C(0 V) sum pF | C(%.1f V) sum pF | vs %.0f pF target | leak nd2ps A | leak pd2nw A |" % (g["v_rev"], g["cap_target_f"] * 1e12))
        w("|---|---|---|---|---|---|---|")
        capsum = []
        for c in corners:
            kd = {d: binding[d][0] for d in g["devices"]}
            c0 = sum(mval(c, "c0", "c_%s_%s" % (d, aname(kd[d]))) or float("nan") for d in kd)
            c5 = sum(mval(c, "c55", "c_%s_%s" % (d, aname(kd[d]))) or float("nan") for d in kd)
            lk = {d: mval(c, "leak", "i_%s_%s" % (d, aname(kd[d]))) for d in kd}
            capsum.append(max(c0, c5))
            verdict = "within" if max(c0, c5) <= g["cap_target_f"] else "ABOVE"
            w("| %s | %s | %.3f | %.3f | %s | %.3g | %.3g |" % (c[0], c[1], c0 * 1e12, c5 * 1e12, verdict, lk["nd"], lk["pd"]))
        w("")
        w("Worst-case summed capacitance: %.3f pF." % (max(capsum) * 1e12))
    w("")

    # I-V tables
    w("## Forward I-V tables (V at the stated current; rows = swept area)")
    for d, model in g["devices"].items():
        for c in corners:
            w("")
            w("### %s, %s, %s C" % (model, c[0], c[1]))
            w("")
            w("| area um^2 | " + " | ".join("%g A" % i for i in g["currents_a"]) + " |")
            w("|---|" + "---|" * len(g["currents_a"]))
            for k in range(0, len(areas)):
                vs = [val(c, "v_%s_%s_i%d" % (d, aname(k), j)) for j in range(len(g["currents_a"]))]
                w("| %.3g | " % (areas[k] * 1e12) + " | ".join("-" if v is None else "%.3f" % v for v in vs) + " |")
    w("")
    w("## Reverse leakage and capacitance vs area (all corners)")
    for d, model in g["devices"].items():
        w("")
        w("### %s" % model)
        w("")
        w("| area um^2 | " + " | ".join("%s/%sC leak A" % c for c in corners) + " |")
        w("|---|" + "---|" * len(corners))
        for k in range(len(areas)):
            w("| %.3g | " % (areas[k] * 1e12) + " | ".join(
                "%.3g" % (mval(c, "leak", "i_%s_%s" % (d, aname(k))) or float("nan")) for c in corners) + " |")
        w("")
        w("| area um^2 | " + " | ".join("%s/%sC C0 / C5.5 fF" % c for c in corners) + " |")
        w("|---|" + "---|" * len(corners))
        for k in range(len(areas)):
            cells = []
            for c in corners:
                c0 = mval(c, "c0", "c_%s_%s" % (d, aname(k)))
                c5 = mval(c, "c55", "c_%s_%s" % (d, aname(k)))
                cells.append("%.1f / %.1f" % ((c0 or float("nan")) * 1e15, (c5 or float("nan")) * 1e15))
            w("| %.3g | " % (areas[k] * 1e12) + " | ".join(cells) + " |")
    text = "\n".join(out) + "\n"
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "record.md"), "w") as f:
        f.write(text)
    summary = {"budget_v": BUDGET, "i_hbm_a": g["i_hbm_a"],
               "binding": {d: (None if binding[d][0] == "none" else
                               {"area_m2": areas[binding[d][0]], "process": binding[d][1][0],
                                "temp_c": binding[d][1][1]}) for d in g["devices"]},
               "worst_cap_f": None if capsum is None else max(capsum)}
    with open(os.path.join(a.out, "summary.json"), "w") as f:
        json.dump(summary, f, indent=1)
    return wording_check([a.out])


# ------------------------------------------------------------ wording check

WORD = re.compile(r"\b(rated|qualified)\b", re.I)


def wording_offenders(text, quote_lines):
    """Lines matching the forbidden words that are not part of the quoted limitation."""
    bad = []
    for n, l in enumerate(text.split("\n"), 1):
        if WORD.search(l) and not (l.startswith("> ") and l[2:] in quote_lines):
            bad.append((n, l))
    return bad


def wording_check(paths):
    quote, _, _ = spec_quote()
    files = []
    for p in paths:
        if os.path.isdir(p):
            files += [os.path.join(p, f) for f in sorted(os.listdir(p)) if f.endswith((".md", ".json", ".txt"))]
        else:
            files.append(p)
    rc = 0
    for f in files:
        for n, l in wording_offenders(open(f).read(), quote):
            print("wording-check: FAIL %s:%d: %s" % (f, n, l), file=sys.stderr)
            rc = 1
    # the record must carry the quotation verbatim
    rec = [f for f in files if f.endswith("record.md")]
    for f in rec:
        t = open(f).read()
        if "\n".join("> " + l for l in quote) not in t:
            print("wording-check: FAIL %s: limitation quote missing or altered" % f, file=sys.stderr)
            rc = 1
    return rc


def selftest():
    quote, _, _ = spec_quote()
    good = "\n".join("> " + l for l in quote)
    assert not wording_offenders(good, quote), "quote must be accepted"
    assert wording_offenders(good + "\nthis part is rated for HBM", quote), "must flag 'rated'"
    assert wording_offenders("Qualified.", quote), "must flag 'Qualified' (case-insensitive)"
    assert not wording_offenders("generated, separated, operated, integrated", quote), "word boundaries"
    assert wording_offenders("> " + quote[0] + " rated", quote), "altered quote line must be flagged"
    # derivation edge: no swept area meets the budget -> None, not interpolated
    assert first_ok([5.0, 4.0, 3.5], 3.0) is None
    assert first_ok([5.0, 2.9, 2.0], 3.0) == 1
    assert first_ok([None, 2.9], 3.0) == 1
    print("selftest: PASS")
    return 0


def main():
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest="cmd", required=True)
    g = sp.add_parser("gen")
    g.add_argument("--out", required=True)
    g.add_argument("--pdk-root")
    g.add_argument("--backend")
    g.add_argument("--bad-lib", action="store_true")
    d = sp.add_parser("derive")
    for k in ("fwd", "leak", "cap"):
        d.add_argument("--" + k, required=True, help="klt sim report for the %s request" % k)
    d.add_argument("--grid", required=True)
    d.add_argument("--out", required=True)
    d.add_argument("--meta", nargs="*", default=[])
    w = sp.add_parser("wording-check")
    w.add_argument("paths", nargs="+")
    sp.add_parser("selftest")
    a = ap.parse_args()
    if a.cmd == "gen":
        cmd_gen(a)
        return 0
    if a.cmd == "derive":
        return cmd_derive(a)
    if a.cmd == "wording-check":
        return wording_check(a.paths)
    return selftest()


if __name__ == "__main__":
    sys.exit(main())
