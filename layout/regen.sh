#!/usr/bin/env bash
# Regenerate the ring GDS and the item-2 envelope, and prove reproducibility.
#   layout/regen.sh           # regenerate, write manifests/evidence/item2.json
#   layout/regen.sh --check   # regenerate to a scratch copy; fail if it differs
set -euo pipefail
cd "$(dirname "$0")/.."
GDS=layout/gf180_io_ring.gds
if [ "${1:-}" = "--check" ]; then
  want=$(sha256sum "$GDS" | cut -d' ' -f1)
  cp "$GDS" "$GDS.committed"
  klayout -b -r layout/gen_ring.py >/dev/null
  got=$(sha256sum "$GDS" | cut -d' ' -f1)
  mv "$GDS.committed" "$GDS"
  [ "$want" = "$got" ] || { echo "layout is stale: committed $want, regenerated $got" >&2; exit 1; }
  echo "reproducible: sha256:$got"
  exit 0
fi
klayout -b -r layout/gen_ring.py >/dev/null
first=$(sha256sum "$GDS" | cut -d' ' -f1)
klayout -b -r layout/gen_ring.py >/dev/null
second=$(sha256sum "$GDS" | cut -d' ' -f1)
[ "$first" = "$second" ] || { echo "generator is not byte-stable" >&2; exit 1; }
python3 -I - "$second" "$(klayout -v | head -1)" <<'PY'
import json, sys
h, kv = "sha256:" + sys.argv[1], sys.argv[2]
env = {
    "schema_version": 1, "kind": "generic", "status": "pass", "t1_item": 2,
    "summary": "T1 item 2 (Layout): committed ring GDS generated by "
               "layout/gen_ring.py; regenerated twice, byte-identical",
    "source": "layout/gf180_io_ring.gds",
    "provenance": {
        "klt_version": "0.8.0", "klayout_version": kv.replace("KLayout ", ""),
        "pdk": "open_pdks f6eeac7dad085ffcc829ccfd721f7b4ce39edcf7 (gf180mcuD)",
        "deck": None,
        "input": {"path": {"path": "layout/gf180_io_ring.gds", "scope": "repo"},
                  "content_hash": h},
        "regeneration": {"generator": "klayout -b -r layout/gen_ring.py",
                         "regenerated_hash": h},
    },
}
open("manifests/evidence/item2.json", "w").write(json.dumps(env, indent=2) + "\n")
print("item2 envelope:", h)
PY
